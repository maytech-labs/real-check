//! `cargo xtask notices`: THIRD-PARTY-NOTICES.md, the licenses of every
//! crate built into real-check, which their licenses require with each copy
//! of the binary.

use std::collections::{BTreeMap, BTreeSet, HashMap};
use std::path::Path;
use std::process::{Command, ExitCode};

use serde_json::Value;

const OUTPUT: &str = "THIRD-PARTY-NOTICES.md";

/// Writes the file, or with `--check`, fails if it's out of date.
pub fn run(args: Vec<String>) -> ExitCode {
    let check = args.iter().any(|a| a == "--check");
    let text = match render() {
        Ok(text) => text,
        Err(error) => {
            eprintln!("notices: {error}");
            return ExitCode::FAILURE;
        }
    };
    if check {
        let current = std::fs::read_to_string(OUTPUT).unwrap_or_default();
        if current != text {
            eprintln!("{OUTPUT} is out of date: run `cargo xtask notices`");
            return ExitCode::FAILURE;
        }
        return ExitCode::SUCCESS;
    }
    match std::fs::write(OUTPUT, text) {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("notices: can't write {OUTPUT}: {error}");
            ExitCode::FAILURE
        }
    }
}

fn render() -> Result<String, String> {
    let output = Command::new(env!("CARGO"))
        .args(["metadata", "--format-version", "1", "--locked"])
        .output()
        .map_err(|e| format!("can't run cargo metadata: {e}"))?;
    if !output.status.success() {
        return Err(String::from_utf8_lossy(&output.stderr).into_owned());
    }
    let metadata: Value =
        serde_json::from_slice(&output.stdout).map_err(|e| format!("bad cargo metadata: {e}"))?;
    let packages: HashMap<&str, &Value> = metadata["packages"]
        .as_array()
        .into_iter()
        .flatten()
        .filter_map(|p| Some((p["id"].as_str()?, p)))
        .collect();
    let nodes: HashMap<&str, &Value> = metadata["resolve"]["nodes"]
        .as_array()
        .into_iter()
        .flatten()
        .filter_map(|n| Some((n["id"].as_str()?, n)))
        .collect();
    // What the binary links: normal dependencies, from real-check down.
    // Build scripts and tests aren't shipped.
    let roots: Vec<&str> = packages
        .iter()
        .filter(|(_, p)| matches!(p["name"].as_str(), Some("real-check")))
        .map(|(id, _)| *id)
        .collect();
    let mut seen: BTreeSet<&str> = BTreeSet::new();
    let mut work = roots;
    while let Some(id) = work.pop() {
        if !seen.insert(id) {
            continue;
        }
        let Some(node) = nodes.get(id) else {
            continue;
        };
        for dep in node["deps"].as_array().into_iter().flatten() {
            let normal = dep["dep_kinds"]
                .as_array()
                .into_iter()
                .flatten()
                .any(|k| k["kind"].is_null());
            if let (true, Some(next)) = (normal, dep["pkg"].as_str()) {
                work.push(next);
            }
        }
    }
    let mut third_party: BTreeMap<(String, String), &Value> = BTreeMap::new();
    for id in seen {
        let Some(package) = packages.get(id) else {
            continue;
        };
        // Our own crate is under LICENSE.md.
        if package["source"].is_null() {
            continue;
        }
        let name = package["name"].as_str().unwrap_or_default().to_string();
        let version = package["version"].as_str().unwrap_or_default().to_string();
        third_party.insert((name, version), package);
    }
    let mut out = String::from(
        "# Third-party notices\n\nThe real-check binary includes these crates. Their licenses, as each crate ships them, follow. Generated by `cargo xtask notices` from Cargo.lock; don't edit by hand.\n",
    );
    for ((name, version), package) in &third_party {
        let license = package["license"].as_str().unwrap_or("see below");
        let repository = package["repository"].as_str().unwrap_or("");
        out.push_str(&format!("\n## {name} {version}\n\nLicense: {license}"));
        if !repository.is_empty() {
            out.push_str(&format!(". Source: {repository}"));
        }
        out.push('\n');
        let dir = Path::new(package["manifest_path"].as_str().unwrap_or_default())
            .parent()
            .map(Path::to_path_buf)
            .unwrap_or_default();
        let mut files: Vec<_> = std::fs::read_dir(&dir)
            .map_err(|e| format!("can't read {}: {e}", dir.display()))?
            .flatten()
            .map(|e| e.file_name().to_string_lossy().into_owned())
            .filter(|f| {
                let upper = f.to_ascii_uppercase();
                upper.starts_with("LICENSE")
                    || upper.starts_with("LICENCE")
                    || upper.starts_with("COPYING")
                    || upper.starts_with("NOTICE")
                    || upper.starts_with("UNLICENSE")
            })
            .collect();
        files.sort();
        if files.is_empty() {
            out.push_str(
                "\nThe crate ships no license file; its license is the one named above.\n",
            );
        }
        for file in files {
            let text = std::fs::read_to_string(dir.join(&file))
                .map_err(|e| format!("can't read {file} of {name}: {e}"))?;
            out.push_str(&format!(
                "\n### {file}\n\n```text\n{}\n```\n",
                text.trim_end()
            ));
        }
    }
    Ok(out)
}
